CREATE TABLE USUARIO (
    ID_USUARIO   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME         VARCHAR2(100)  NOT NULL,
    EMAIL        VARCHAR2(150)  NOT NULL,
    SENHA        VARCHAR2(255)  NOT NULL,
    ATIVO        CHAR(1)        DEFAULT 'S' NOT NULL,
    DATA_CADASTRO TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UK_USUARIO_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USUARIO_ATIVO CHECK (ATIVO IN ('S', 'N'))
);

CREATE TABLE CATEGORIA (
    ID_CATEGORIA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME         VARCHAR2(80)   NOT NULL,
    DESCRICAO    VARCHAR2(255),
    ATIVO        CHAR(1)        DEFAULT 'S' NOT NULL,
    CONSTRAINT PK_CATEGORIA PRIMARY KEY (ID_CATEGORIA),
    CONSTRAINT UK_CATEGORIA_NOME UNIQUE (NOME),
    CONSTRAINT CK_CATEGORIA_ATIVO CHECK (ATIVO IN ('S', 'N'))
);

CREATE TABLE OCORRENCIA (
    ID_OCORRENCIA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO    NUMBER         NOT NULL,
    ID_CATEGORIA  NUMBER         NOT NULL,
    TITULO        VARCHAR2(120)  NOT NULL,
    DESCRICAO     VARCHAR2(1000),
    LATITUDE      NUMBER(9,6),
    LONGITUDE     NUMBER(9,6),
    ENDERECO      VARCHAR2(255),
    PROTOCOLO     VARCHAR2(30)   NOT NULL,
    STATUS_ATUAL  VARCHAR2(20)   DEFAULT 'ABERTA' NOT NULL,
    DATA_ABERTURA TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_OCORRENCIA PRIMARY KEY (ID_OCORRENCIA),
    CONSTRAINT UK_OCORRENCIA_PROTOCOLO UNIQUE (PROTOCOLO),
    CONSTRAINT FK_OCORRENCIA_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT FK_OCORRENCIA_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES CATEGORIA (ID_CATEGORIA),
    CONSTRAINT CK_OCORRENCIA_STATUS CHECK (STATUS_ATUAL IN
        ('ABERTA', 'EM_ANALISE', 'EM_ANDAMENTO', 'RESOLVIDA', 'REJEITADA')),
    CONSTRAINT CK_OCORRENCIA_LATITUDE CHECK (LATITUDE BETWEEN -90 AND 90),
    CONSTRAINT CK_OCORRENCIA_LONGITUDE CHECK (LONGITUDE BETWEEN -180 AND 180)
);

CREATE TABLE FOTO_OCORRENCIA (
    ID_FOTO       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_OCORRENCIA NUMBER         NOT NULL,
    URL_FOTO      VARCHAR2(500)  NOT NULL,
    DATA_ENVIO    TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_FOTO_OCORRENCIA PRIMARY KEY (ID_FOTO),
    CONSTRAINT FK_FOTO_OCORRENCIA FOREIGN KEY (ID_OCORRENCIA) REFERENCES OCORRENCIA (ID_OCORRENCIA)
);

CREATE TABLE HISTORICO_STATUS (
    ID_HISTORICO    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_OCORRENCIA   NUMBER         NOT NULL,
    ID_USUARIO      NUMBER         NOT NULL,
    STATUS_ANTERIOR VARCHAR2(20),
    STATUS_NOVO     VARCHAR2(20)   NOT NULL,
    OBSERVACAO      VARCHAR2(500),
    DATA_ALTERACAO  TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_HISTORICO_STATUS PRIMARY KEY (ID_HISTORICO),
    CONSTRAINT FK_HISTORICO_OCORRENCIA FOREIGN KEY (ID_OCORRENCIA) REFERENCES OCORRENCIA (ID_OCORRENCIA),
    CONSTRAINT FK_HISTORICO_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT CK_HISTORICO_STATUS_NOVO CHECK (STATUS_NOVO IN
        ('ABERTA', 'EM_ANALISE', 'EM_ANDAMENTO', 'RESOLVIDA', 'REJEITADA'))
);

CREATE TABLE APOIO_OCORRENCIA (
    ID_APOIO      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO    NUMBER         NOT NULL,
    ID_OCORRENCIA NUMBER         NOT NULL,
    TIPO_APOIO    VARCHAR2(20)   NOT NULL,
    DATA_APOIO    TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_APOIO_OCORRENCIA PRIMARY KEY (ID_APOIO),
    CONSTRAINT UK_APOIO_USUARIO_OCORRENCIA UNIQUE (ID_USUARIO, ID_OCORRENCIA),
    CONSTRAINT FK_APOIO_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT FK_APOIO_OCORRENCIA FOREIGN KEY (ID_OCORRENCIA) REFERENCES OCORRENCIA (ID_OCORRENCIA),
    CONSTRAINT CK_APOIO_TIPO CHECK (TIPO_APOIO IN ('APOIO', 'CONFIRMACAO'))
);

CREATE TABLE NOTIFICACAO (
    ID_NOTIFICACAO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO     NUMBER         NOT NULL,
    ID_OCORRENCIA  NUMBER,
    TITULO         VARCHAR2(120)  NOT NULL,
    MENSAGEM       VARCHAR2(500)  NOT NULL,
    LIDA           CHAR(1)        DEFAULT 'N' NOT NULL,
    DATA_ENVIO     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_NOTIFICACAO PRIMARY KEY (ID_NOTIFICACAO),
    CONSTRAINT FK_NOTIFICACAO_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT FK_NOTIFICACAO_OCORRENCIA FOREIGN KEY (ID_OCORRENCIA) REFERENCES OCORRENCIA (ID_OCORRENCIA),
    CONSTRAINT CK_NOTIFICACAO_LIDA CHECK (LIDA IN ('S', 'N'))
);

-- Indices das consultas mais usadas (FKs e filtros do app)
CREATE INDEX IX_OCORRENCIA_USUARIO   ON OCORRENCIA (ID_USUARIO);
CREATE INDEX IX_OCORRENCIA_CATEGORIA ON OCORRENCIA (ID_CATEGORIA);
CREATE INDEX IX_OCORRENCIA_STATUS    ON OCORRENCIA (STATUS_ATUAL);
CREATE INDEX IX_FOTO_OCORRENCIA      ON FOTO_OCORRENCIA (ID_OCORRENCIA);
CREATE INDEX IX_HISTORICO_OCORRENCIA ON HISTORICO_STATUS (ID_OCORRENCIA);
CREATE INDEX IX_APOIO_OCORRENCIA     ON APOIO_OCORRENCIA (ID_OCORRENCIA);
CREATE INDEX IX_NOTIFICACAO_USUARIO  ON NOTIFICACAO (ID_USUARIO, LIDA);
