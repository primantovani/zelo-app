-- Total de linhas por tabela
SELECT 'USUARIO' AS TABELA, COUNT(*) AS TOTAL FROM USUARIO
UNION ALL
SELECT 'CATEGORIA', COUNT(*) FROM CATEGORIA
UNION ALL
SELECT 'OCORRENCIA', COUNT(*) FROM OCORRENCIA
UNION ALL
SELECT 'FOTO_OCORRENCIA', COUNT(*) FROM FOTO_OCORRENCIA
UNION ALL
SELECT 'HISTORICO_STATUS', COUNT(*) FROM HISTORICO_STATUS
UNION ALL
SELECT 'APOIO_OCORRENCIA', COUNT(*) FROM APOIO_OCORRENCIA
UNION ALL
SELECT 'NOTIFICACAO', COUNT(*) FROM NOTIFICACAO;

-- Ocorrencias com cidadao e categoria
SELECT
    O.ID_OCORRENCIA,
    O.PROTOCOLO,
    O.TITULO,
    U.NOME AS CIDADAO,
    C.NOME AS CATEGORIA,
    O.STATUS_ATUAL,
    O.ENDERECO
FROM OCORRENCIA O
INNER JOIN USUARIO U
    ON O.ID_USUARIO = U.ID_USUARIO
INNER JOIN CATEGORIA C
    ON O.ID_CATEGORIA = C.ID_CATEGORIA
ORDER BY O.ID_OCORRENCIA;

-- Historico de uma ocorrencia, com o responsavel por cada mudanca
SELECT
    H.ID_OCORRENCIA,
    H.STATUS_ANTERIOR,
    H.STATUS_NOVO,
    H.OBSERVACAO,
    H.DATA_ALTERACAO,
    U.NOME AS RESPONSAVEL
FROM HISTORICO_STATUS H
INNER JOIN USUARIO U
    ON H.ID_USUARIO = U.ID_USUARIO
WHERE H.ID_OCORRENCIA = 1
ORDER BY H.DATA_ALTERACAO;
